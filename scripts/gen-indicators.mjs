#!/usr/bin/env node
// gen-indicators.mjs: writes what the am-i-pwned skill shows of src/rules/indicators.json, so Ficus and the skill read one list.
//
//   node scripts/gen-indicators.mjs           rewrite docs/am-i-pwned/references/known-indicators.md and the generated
//                                              block of docs/am-i-pwned/mac-triage.sh
//   node scripts/gen-indicators.mjs --check   change nothing; exit 1 if either file is out of date (a test runs this)
//
// Edit indicators.json, then run this. Never edit the generated page or the block by hand.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'src/rules/indicators.json');
const PAGE = path.join(ROOT, 'docs/am-i-pwned/references/known-indicators.md');
const SCRIPT = path.join(ROOT, 'docs/am-i-pwned/mac-triage.sh');
export const BEGIN = '# BEGIN GENERATED INDICATORS (scripts/gen-indicators.mjs, from src/rules/indicators.json: edit that file, not this block)';
export const END = '# END GENERATED INDICATORS';

const KIND_WORDS = {
  'team-id': 'signing team', 'signing-id': 'signing ID', path: 'path', plist: 'launch plist', argv: 'command-line word',
};
const cell = s => s.replace(/\|/g, '\\|');

/** The skill's reference page. */
export function renderPage(data) {
  const out = [
    '# Known actor indicators',
    '',
    '<!-- Generated by scripts/gen-indicators.mjs from src/rules/indicators.json. Edit that file and run the script; do not edit this page. -->',
    '',
    data.about,
    '',
    `Last updated ${data.updated}. ${data.pathSyntax}`,
    '',
    '## How to use it',
    '',
    '- `mac-triage.sh` (section 10) looks for the **paths, launch plists, signing teams and signing IDs** below on this Mac and prints each match with its family. It cannot read command lines (they are off limits), so the *command-line word* entries are for a Ficus capture.',
    '- A match with a **high** entry is a finding at level 3 of *Choosing the verdict* (`reading-the-result.md`); a match with a **medium** entry is level 2. Say which family and which entry, and quote the source.',
    '- **No match proves nothing.** A family renames its files between samples, a list ages, and a Mac can be compromised by a family that is not here. Never say a Mac is clean because this list found nothing.',
    '- Never use an indicator from memory. If this page is not in front of you, say the check was not done.',
    '- **Attribution is the vendor\'s, with its own confidence.** Where a family\'s actor is tentative or not named, the table says so; do not tell the person a state actor is behind it unless the row says so.',
    '',
  ];
  for (const f of data.families) {
    out.push(`## ${f.name}`, '', `**Actor:** ${f.actor}. **Attribution:** ${f.attribution}.`, '', f.summary, '',
      '| Kind | Value | Severity | Confidence | What it is | Source |', '| --- | --- | --- | --- | --- | --- |');
    for (const i of f.indicators) {
      out.push(`| ${KIND_WORDS[i.kind]} | \`${cell(i.value)}\` | ${i.severity} | ${i.confidence} | ${cell(i.note ?? '')} | ${i.source} |`);
    }
    out.push('');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

/** The path forms the script can look for with a shell glob: no `**` (any depth) and no command-line words. */
export function scriptEntries(data) {
  const ids = [];
  const paths = [];
  for (const f of data.families) {
    for (const i of f.indicators) {
      const v = i.value;
      if (/['|\n]/.test(v) || /['|\n]/.test(f.name)) throw new Error(`indicator value or family name holds a character the script cannot carry: ${f.name}: ${v}`);
      if (i.kind === 'team-id') ids.push(`team|${f.name}|${i.severity}|${v}`);
      else if (i.kind === 'signing-id') ids.push(`signing|${f.name}|${i.severity}|${v}`);
      else if (i.kind === 'plist') {
        for (const dir of ['/Library/LaunchAgents', '/Library/LaunchDaemons', '~/Library/LaunchAgents']) paths.push(`${f.name}|${i.severity}|${dir}/${v}`);
      } else if (i.kind === 'path' && !v.includes('**')) paths.push(`${f.name}|${i.severity}|${v}`);
    }
  }
  return { ids, paths };
}

/** The block between the markers of mac-triage.sh, markers included. */
export function renderBlock(data) {
  const { ids, paths } = scriptEntries(data);
  return [
    BEGIN,
    '# kind|family|severity|value (kind: team = code-signing team ID, signing = signing identifier)',
    `KNOWN_IDS='${ids.join('\n')}'`,
    '# family|severity|path (a leading ~/ is the home folder, * is a glob, a trailing / is a folder)',
    `KNOWN_PATHS='${paths.join('\n')}'`,
    END,
  ].join('\n');
}

/** The script with its generated block replaced. */
export function replaceBlock(script, block) {
  const a = script.indexOf(BEGIN);
  const b = script.indexOf(END);
  if (a < 0 || b < a) throw new Error('mac-triage.sh has no generated-indicators block between its markers');
  return script.slice(0, a) + block + script.slice(b + END.length);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));
  const next = { page: renderPage(data), script: replaceBlock(fs.readFileSync(SCRIPT, 'utf8'), renderBlock(data)) };
  const current = { page: fs.existsSync(PAGE) ? fs.readFileSync(PAGE, 'utf8') : '', script: fs.readFileSync(SCRIPT, 'utf8') };
  const stale = Object.keys(next).filter(k => next[k] !== current[k]);
  if (process.argv.includes('--check')) {
    if (stale.length > 0) { console.error(`out of date: ${stale.join(', ')}. Run: node scripts/gen-indicators.mjs`); process.exit(1); }
  } else {
    fs.writeFileSync(PAGE, next.page);
    fs.writeFileSync(SCRIPT, next.script);
    console.log(stale.length > 0 ? `updated ${stale.join(', ')}` : 'already up to date');
  }
}
